    private String limpiar(String texto) {
        if (texto == null) {
            return "";
        }
        String n = java.text.Normalizer.normalize(texto, java.text.Normalizer.Form.NFD);
        return n.replaceAll("[^\\p{ASCII}]", "").replaceAll("[^A-Za-z]", "").toUpperCase();
    }

    private char primeraVocalInterna(String palabra) {
        for (int i = 1; i < palabra.length(); i++) {
            if ("AEIOU".indexOf(palabra.charAt(i)) >= 0) {
                return palabra.charAt(i);
            }
        }
        return 'X';
    }

    private boolean esPalabraInconveniente(String s) {
        String[] malas = {"BACA", "BAKA", "CACA", "CAGA", "COGE", "COJA", "CULO", "FALO",
            "JOTO", "LOCA", "LOCO", "MEAR", "MEON", "MOCO", "MULA", "NACO",
            "PEDA", "PEDO", "PENE", "PITO", "PUTA", "PUTO", "RATA", "SEXO",
            "SENO", "TETA", "VACA", "VAGA", "VAGO", "WUEY", "BUEY", "GUEY"};
        for (String m : malas) {
            if (m.equals(s)) {
                return true;
            }
        }
        return false;
    }

    private void cargarEstados() {
        try {
            Connection c = Conexion.getConnection();
            PreparedStatement ps = c.prepareStatement("select id,nombre,clave from Entidades");
            ResultSet rs = ps.executeQuery();
            while (rs.next()) {
                cbEntidadNac.addItem(rs.getString("nombre"));
            }
        } catch (SQLException ex) {
            Logger.getLogger(Estados.class.getName()).log(Level.SEVERE, null, ex);
        }
    }

    public void cargarDatos() {
        DefaultTableModel dtm = (DefaultTableModel) jtUsuarios.getModel();
        dtm.setRowCount(0);
        Connection c = Conexion.getConnection();
        try {
            PreparedStatement ps = c.prepareStatement("Select curp, nombre, aPaterno, aMaterno, fechaNac, entidadNac, sexo, telefono, email from [127.0.0.1].[CITAS_INE].[dbo].[Usuarios] order by curp");
            ResultSet rs = ps.executeQuery();
            ResultSetMetaData rsmd = rs.getMetaData();
            int columnas = rsmd.getColumnCount();
            while (rs.next()) {
                Object[] Fila = new Object[columnas];
                for (int i = 0; i < columnas; i++) {
                    Fila[i] = rs.getObject(i + 1);
                }
                dtm.addRow(Fila);
            }
        } catch (SQLException ex) {
            Logger.getLogger(usuarios.class.getName()).log(Level.SEVERE, null, ex);
        }
    }

