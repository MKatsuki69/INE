    private void jbCurpActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbCurpActionPerformed
        // TODO add your handling code here
        try {
            String ap = limpiar(txtAPaterno.getText().trim());
            String am = limpiar(txtAMaterno.getText().trim());
            String nom = limpiar(txtNombre.getText().trim());
            String sexo = cbSexo.getSelectedItem().toString().trim();

            if (ap.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Apellido paterno requerido.");
                return;
            }
            if (nom.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Nombre requerido.");
                return;
            }
            if (nacimiento.getDate() == null) {
                JOptionPane.showMessageDialog(this, "Fecha requerida.");
                return;
            }
            if (sexo.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Elija su sexo.");
                return;
            }

            // --- Parte 1: 4 letras ---
            char c1 = ap.charAt(0);
            char c2 = primeraVocalInterna(ap);
            char c3 = am.isEmpty() ? 'X' : am.charAt(0);
            char c4 = nom.charAt(0);
            String parte1 = "" + c1 + c2 + c3 + c4;
            if (esPalabraInconveniente(parte1)) {
                parte1 = parte1.charAt(0) + "X" + parte1.substring(2);
            }

            // --- Parte 2: Fecha AAMMDD desde jDateChooser ---
            java.util.Calendar cal = java.util.Calendar.getInstance();
            cal.setTime(nacimiento.getDate());
            String anio = String.valueOf(cal.get(java.util.Calendar.YEAR)).substring(2);
            String mes = String.format("%02d", cal.get(java.util.Calendar.MONTH) + 1);
            String dia = String.format("%02d", cal.get(java.util.Calendar.DAY_OF_MONTH));
            String parte2 = anio + mes + dia;

            // --- Parte 3: Sexo ---
            String curp = parte1 + parte2 + sexo;
            txtCurp.setText(curp);

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al generar CURP: " + e.getMessage());
        }
    }//GEN-LAST:event_jbCurpActionPerformed

    private void jbGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbGuardarActionPerformed
        // TODO add your handling code here:
        try {
            String curp = txtCurp.getText().trim();
            String nombre = txtNombre.getText().trim();
            String ap = txtAPaterno.getText().trim();
            String am = txtAMaterno.getText().trim();
            String sexo = cbSexo.getSelectedItem().toString().trim();
            String telefono = txtTelefono.getText().trim();
            String email = txtEmail.getText().trim();

            if (curp.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Genera la CURP primero.");
                return;
            }
            if (nombre.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Nombre requerido.");
                return;
            }
            if (ap.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Apellido paterno requerido.");
                return;
            }
            if (am.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Apellido materno requerido.");
                return;
            }
            if (telefono.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Teléfono requerido.");
                return;
            }
            if (nacimiento.getDate() == null) {
                JOptionPane.showMessageDialog(this, "Fecha requerida.");
                return;
            }

            java.sql.Date fechaNac = new java.sql.Date(nacimiento.getDate().getTime());
            String nombreEntidad = cbEntidadNac.getSelectedItem().toString();

            Connection con = Conexion.getConnection();

            // Buscar ID de la entidad
            int entidadNac = 0;
            PreparedStatement psEnt = con.prepareStatement("SELECT id FROM Entidades WHERE nombre = ?");
            psEnt.setString(1, nombreEntidad);
            ResultSet rs = psEnt.executeQuery();
            if (rs.next()) {
                entidadNac = rs.getInt("id");
            } else {
                JOptionPane.showMessageDialog(this, "Entidad no encontrada.");
                return;
            }
            rs.close();
            psEnt.close();

            // Insertar usuario
            String sql = "INSERT INTO [127.0.0.1].[CITAS_INE].[dbo].[Usuarios] (curp, nombre, aPaterno, aMaterno, fechaNac, entidadNac, sexo, telefono, email) "
                    + "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)";

            PreparedStatement ps = con.prepareStatement(sql);
            ps.setString(1, curp);
            ps.setString(2, nombre);
            ps.setString(3, ap);
            ps.setString(4, am);
            ps.setDate(5, fechaNac);
            ps.setInt(6, entidadNac);
            ps.setString(7, sexo);
            ps.setString(8, telefono);
            ps.setString(9, email.isEmpty() ? null : email);

            ps.executeUpdate();
            ps.close();
            con.close();

            JOptionPane.showMessageDialog(this, "Usuario guardado correctamente.");
            limpiarDatos();
            cargarDatos();
        } catch (Exception e) {
            if (e.getMessage() != null && e.getMessage().contains("PRIMARY KEY")) {
                JOptionPane.showMessageDialog(this, "Ya existe un usuario con esa CURP.");
            } else {
                JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
            }
        }

    }//GEN-LAST:event_jbGuardarActionPerformed

