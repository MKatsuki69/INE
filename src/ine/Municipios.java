    private void jtMunicipiosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jtMunicipiosMouseClicked
        int id = Integer.parseInt(jtMunicipios.getValueAt(jtMunicipios.getSelectedRow(), 0) + "");
        try {
            Connection c = Conexion.getConnection();
            PreparedStatement ps = c.prepareStatement("select id, nombre, idEntidad from [127.0.0.1].[CITAS_INE].[dbo].[Municipio] where id=?");
            ps.setInt(1, id);
            ResultSet rs = ps.executeQuery();
            while (rs.next()) {
                jcbEstados.setSelectedIndex(Integer.parseInt(rs.getString("idEntidad")) - 1);
                jtfNombre.setText(rs.getString("Nombre"));
                jtfIdMunicipio.setText(rs.getInt("id") + "");
            }
        } catch (SQLException ex) {
            Logger.getLogger(Estados.class.getName()).log(Level.SEVERE, null, ex);

        }
    }//GEN-LAST:event_jtMunicipiosMouseClicked

