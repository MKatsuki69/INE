    private void jbEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbEliminarActionPerformed
        if (jtfIdMunicipio.getText().equals("")) {
            JOptionPane.showMessageDialog(null, "ERROR:Debe seleccionar un Municipio válido");
        } else {
            int idMunicipio = Integer.parseInt(jtfIdMunicipio.getText());
            Connection c = Conexion.getConnection();
            try {
                java.sql.PreparedStatement ps = c.prepareStatement("Delete from Municipio where id=?");
                ps.setInt(1, idMunicipio);
                ps.executeUpdate();
                JOptionPane.showMessageDialog(null, "Registro Eliminado con Éxito");
                limpiar();
                cargarDatos();
            } catch (SQLException ex) {
                JOptionPane.showMessageDialog(null, "Error " + ex.getMessage());
            }
        }
    }//GEN-LAST:event_jbEliminarActionPerformed

    private void jbModidicarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbModidicarActionPerformed
        if (jtfIdMunicipio.getText().equals("")) {
            JOptionPane.showMessageDialog(null, "ERROR:Debe seleccionar un Municipio válido");
        } else {
            int idMunicipio = Integer.parseInt(jtfIdMunicipio.getText());
            String nombreMunicipio = jtfNombre.getText();
            String entidad = jcbEstados.getSelectedItem().toString();
            Connection c = Conexion.getConnection();
            try {
                java.sql.PreparedStatement ps = c.prepareStatement("exec spActualizarMunicipio ?, ?, ?");
                ps.setInt(1, idMunicipio);
                ps.setString(2, nombreMunicipio);
                ps.setString(3, entidad);
                ps.executeUpdate();
                JOptionPane.showMessageDialog(null, "Registro Actualizado con Éxito");
                limpiar();
                cargarDatos();
            } catch (SQLException ex) {
                JOptionPane.showMessageDialog(null, "Error " + ex.getMessage());

            }
        }
    }//GEN-LAST:event_jbModidicarActionPerformed

