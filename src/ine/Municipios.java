    public void cargarEstados() {
        try {
            Connection c = Conexion.getConnection();
            PreparedStatement ps = c.prepareStatement("SELECT * FROM Entidades\n" +
"UNION\n" +
"SELECT * FROM [192.168.0.232].[INE_NORTE].[dbo].[Entidades]\n" +
"UNION\n" +
"SELECT * FROM [192.168.0.108].[INE_CENTRO].[dbo].[Entidades]");
            ResultSet rs = ps.executeQuery();
            while (rs.next()) {
                jcbEstados.addItem(rs.getString("nombre"));
            }
        } catch (SQLException ex) {
            Logger.getLogger(Estados.class.getName()).log(Level.SEVERE, null, ex);
        }
    }

    public void cargarDatos() {
        DefaultTableModel dtm = (DefaultTableModel) jtMunicipios.getModel();
        dtm.setRowCount(0);
        Connection c = Conexion.getConnection();
        try {
            PreparedStatement ps = c.prepareStatement("WITH TodasEntidades AS (\n" +
"    SELECT id, nombre \n" +
"    FROM Entidades\n" +
"    UNION\n" +
"    SELECT id, nombre \n" +
"    FROM [192.168.0.232].[INE_NORTE].[dbo].[Entidades]\n" +
"    UNION\n" +
"    SELECT id, nombre \n" +
"    FROM [192.168.0.108].[INE_CENTRO].[dbo].[Entidades]\n" +
")\n" +
"SELECT m.id, m.nombre AS Municipio, e.nombre AS Entidad\n" +
"FROM TodasEntidades e\n" +
"INNER JOIN Municipio m ON e.id = m.idEntidad;");
            ResultSet rs = ps.executeQuery();
            ResultSetMetaData rsmd = rs.getMetaData();
            int columnas = rsmd.getColumnCount();
            while (rs.next()) {
                Object[] Fila = new Object[columnas];
                for (int i = 0; i < columnas; i++) {
                    Fila[i] = rs.getObject(i + 1);
                }
                dtm.addRow(Fila);
            }
        } catch (SQLException ex) {
            Logger.getLogger(Estados.class.getName()).log(Level.SEVERE, null, ex);
        }
    }

