    private void jbGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbGuardarActionPerformed
        try {
            String nombre = jtfNombre.getText();
            String referencia = jtfReferencias.getText();
            String horarioSem = jtfHorarioSem.getText();
            String horarioFin = jtfHorarioFin.getText();
            int idMunicipio = Integer.parseInt(jtfIdMunicipio.getText());
            Connection c = Conexion.getConnection();
            // Usamos parámetros sin comillas
            PreparedStatement ps = c.prepareStatement("exec spInsertarModulo ?, ?, ?, ?, ?");

            // Asignamos los valores a los parámetros
            ps.setString(1, nombre);
            ps.setString(2, referencia);
            ps.setString(3, horarioSem);
            ps.setString(4, horarioFin);
            ps.setInt(5, idMunicipio);

            ps.executeUpdate();

            JOptionPane.showMessageDialog(null, "Registro guardado con Éxito");
            limpiar();
            cargarDatos();
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(null, "Error " + ex.getMessage());
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error " + e.getMessage());
        }
        // TODO add your handling code here:
    }//GEN-LAST:event_jbGuardarActionPerformed

