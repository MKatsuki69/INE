    private void jcbMunicipioActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jcbMunicipioActionPerformed

        String sql = "select m.id idMunicipio from Entidades e inner join [127.0.0.1].[CITAS_INE].[dbo].[Municipio] m on e.id=m.idEntidad where e.nombre like ? and m.nombre like ?";
        try {
            Connection c = Conexion.getConnection();
            PreparedStatement ps = c.prepareStatement(sql);
            ps.setString(1, jcbEstados.getSelectedItem().toString());
            if (jcbMunicipio.getSelectedItem() != null) {
                ps.setString(2, jcbMunicipio.getSelectedItem().toString());
            } else {
                return; // o simplemente no ejecutar la consulta
            }

            ResultSet rs = ps.executeQuery();
            while (rs.next()) {
                jtfIdMunicipio.setText(rs.getString("idMunicipio"));
            }
        } catch (SQLException ex) {
            Logger.getLogger(Estados.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jcbMunicipioActionPerformed

