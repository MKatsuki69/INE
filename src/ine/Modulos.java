    private void jbModidicarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbModidicarActionPerformed
        int id = Integer.parseInt(jtfIdModulo.getText());
        String nombre = jtfNombre.getText();
        String referencia = jtfReferencias.getText();
        String horarioSem = jtfHorarioSem.getText();
        String horarioFin = jtfHorarioFin.getText();
        int idMunicipio = Integer.parseInt(jtfIdMunicipio.getText());
        Connection c = Conexion.getConnection();
        try {
            java.sql.PreparedStatement ps = c.prepareStatement("exec spActualizarModulo ?, ?, ?,?,?,?");
            ps.setInt(1, id);
            ps.setString(2, nombre);
            ps.setString(3, referencia);
            ps.setString(4, horarioSem);
            ps.setString(5, horarioFin);
            ps.setInt(6, idMunicipio);
            ps.executeUpdate();
            JOptionPane.showMessageDialog(null, "Registro Actualizado con Éxito");
            limpiar();
            cargarDatos();
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(null, "Error " + ex.getMessage());

        }
    }//GEN-LAST:event_jbModidicarActionPerformed

