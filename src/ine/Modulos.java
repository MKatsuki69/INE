    public void cargarEstados() {
        try {
            Connection c = Conexion.getConnection();
            PreparedStatement ps = c.prepareStatement("Select id, nombre, clave from Entidades");
            ResultSet rs = ps.executeQuery();
            while (rs.next()) {
                jcbEstados.addItem(rs.getString("nombre"));
            }
            cargarMunicipios();
        } catch (SQLException ex) {
            Logger.getLogger(Estados.class.getName()).log(Level.SEVERE, null, ex);
        }
    }

    public void cargarMunicipios() {
        jcbMunicipio.removeAllItems();
        try {
            Connection c = Conexion.getConnection();
            PreparedStatement ps = c.prepareStatement("Select m.nombre Municipio from [127.0.0.1].[CITAS_INE].[dbo].[Municipio] m inner join Entidades e on m.idEntidad = e.id where e.nombre like ?");
            ps.setString(1, jcbEstados.getSelectedItem().toString());
            ResultSet rs = ps.executeQuery();
            while (rs.next()) {
                jcbMunicipio.addItem(rs.getString("Municipio").toString());
            }
        } catch (SQLException ex) {
            Logger.getLogger(Estados.class.getName()).log(Level.SEVERE, null, ex);
        }
    }

    public void limpiar() {
        jcbEstados.setSelectedIndex(0);
        cargarMunicipios();
        jtfHorarioFin.setText("");
        jtfHorarioSem.setText("");
        jtfNombre.setText("");
        jtfReferencias.setText("");
        jtfIdModulo.setText("");
        jtfIdMunicipio.setText("");
    }

    public void cargarDatos() {
        DefaultTableModel dtm = (DefaultTableModel) jtModulos.getModel();
        dtm.setRowCount(0);
        Connection c = Conexion.getConnection();
        try {
            PreparedStatement ps = c.prepareStatement("Select mo.id, mo.nombre, mo.referencia, mo.horarioSem, mo.horarioFin, m.nombre from [127.0.0.1].[CITAS_INE].[dbo].[Municipio] m inner join [127.0.0.1].[CITAS_INE].[dbo].[Modulo] mo on m.id = mo.idMunicipio inner join [127.0.0.1].[CITAS_INE].[dbo].[Entidades] e on m.idEntidad = e.id where e.nombre like ? ");
            ps.setString(1, jcbEstados.getSelectedItem().toString());
            ResultSet rs = ps.executeQuery();
            ResultSetMetaData rsmd = rs.getMetaData();
            int columnas = rsmd.getColumnCount();
            while (rs.next()) {
                Object[] Fila = new Object[columnas];
                for (int i = 0; i < columnas; i++) {
                    Fila[i] = rs.getObject(i + 1);
                }
                dtm.addRow(Fila);
            }
        } catch (SQLException ex) {
            Logger.getLogger(Estados.class.getName()).log(Level.SEVERE, null, ex);
        }
    }

