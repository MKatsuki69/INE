    private void jtModulosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jtModulosMouseClicked
        int id = Integer.parseInt(jtModulos.getValueAt(jtModulos.getSelectedRow(), 0) + "");
        try {
            Connection c = Conexion.getConnection();
            PreparedStatement ps = c.prepareStatement("select mo.id modulo, mo.nombre nombre, mo.referencia referencia, mo.horarioSem horarioSem, mo.horarioFin horarioFin, m.id idMunicipio, e.id idEntidad from [127.0.0.1].[CITAS_INE].[dbo].[Modulo] mo inner join [127.0.0.1].[CITAS_INE].[dbo].[Municipio] m on mo.idMunicipio = m.id inner join [127.0.0.1].[CITAS_INE].[dbo].[Entidades] e on m.idEntidad = e.id where mo.id=?");
            ps.setInt(1, id);
            ResultSet rs = ps.executeQuery();
            while (rs.next()) {
                jcbEstados.setSelectedIndex(Integer.parseInt(rs.getString("idEntidad")) - 1);
                //jcbMunicipio.setSelectedIndex(Integer.parseInt(rs.getString("idMunicipio")) - 1);
                jtfNombre.setText(rs.getString("nombre"));
                jtfReferencias.setText(rs.getString("referencia"));
                jtfHorarioSem.setText(rs.getString("horarioSem"));
                jtfHorarioFin.setText(rs.getString("horarioFin"));
                jtfIdModulo.setText(rs.getString("modulo"));
            }
        } catch (SQLException ex) {
            Logger.getLogger(Estados.class.getName()).log(Level.SEVERE, null, ex);

        }        // TODO add your handling code here:
    }//GEN-LAST:event_jtModulosMouseClicked

